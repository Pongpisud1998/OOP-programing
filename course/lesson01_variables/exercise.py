# บทที่ 1: ค่าและตัวแปร
#
# รันดูผล:  python lesson01_variables/exercise.py
# ตรวจ:     python check.py 1
#
# ไฟล์นี้ยังไม่แสดงอะไรตอนรัน ถ้าอยากเห็นค่าของตัวแปรไหน ให้เพิ่ม print(ชื่อตัวแปร) เองได้เลย


# ---------- ค่าตั้งต้น ----------
# ข้อมูลของที่ดินจริง 1 แปลงจากไฟล์ข้อมูลของเรา: โฉนดเลขที่ 11304 เนื้อที่ 3 ไร่ 3 งาน 54 ตารางวา
# ห้ามแก้ 5 บรรทัดนี้ ตัวตรวจจะลองเปลี่ยนค่าเหล่านี้เป็นแปลงอื่น เพื่อดูว่าโค้ดของเราคำนวณถูกทุกแปลง
parcel_type = "โฉนด"
parcel_no = 11304
rai = 3
ngan = 3
wa = 54


# ---------- ข้อ 1 ----------
# สร้างตัวแปรชื่อ parcel_count เก็บตัวเลข 40 (จำนวนแปลงที่ดินทั้งหมดในข้อมูล)
parcel_count = 40
print(parcel_count)




# ---------- ข้อ 2 ----------
# 1 ไร่ เท่ากับ 400 ตารางวา
# สร้างตัวแปรชื่อ rai_in_sq_wa เก็บผลของการแปลงค่าในตัวแปร rai เป็นตารางวา
rai_in_sq_wa = rai * 400
print(rai_in_sq_wa)

# ---------- ข้อ 3 ----------
# 1 งาน เท่ากับ 100 ตารางวา
# สร้างตัวแปรชื่อ ngan_in_sq_wa เก็บผลของการแปลงค่าในตัวแปร ngan เป็นตารางวา
ngan_in_sq_wa = ngan * 100
print(ngan_in_sq_wa) 


# ---------- ข้อ 4 ----------
# สร้างตัวแปรชื่อ total_sq_wa เก็บเนื้อที่ทั้งหมดของแปลงนี้ในหน่วยตารางวา
# (ส่วนที่เป็นไร่ บวกส่วนที่เป็นงาน บวกส่วนที่เป็นตารางวา)
total_sq_wa = rai_in_sq_wa + ngan_in_sq_wa + wa
print(total_sq_wa)


# ---------- ข้อ 5 ----------
# 1 ตารางวา เท่ากับ 4 ตารางเมตร
# สร้างตัวแปรชื่อ total_sq_m เก็บเนื้อที่ทั้งหมดของแปลงนี้ในหน่วยตารางเมตร
total_sq_m = total_sq_wa * 4
print(total_sq_m)


# ---------- ข้อ 6 ----------
# สร้างตัวแปรชื่อ label เก็บข้อความที่ประกอบจากตัวแปร parcel_type และ parcel_no
# สำหรับแปลงนี้ต้องได้ข้อความ:  โฉนด เลขที่ 11304
label = f"{parcel_type} เลขที่ {parcel_no}"
print(label)

# ---------- ข้อ 7 ----------
# สร้างตัวแปรชื่อ area_text เก็บข้อความบอกเนื้อที่ ประกอบจากตัวแปร rai, ngan และ wa
# สำหรับแปลงนี้ต้องได้ข้อความ:  3 ไร่ 3 งาน 54 ตารางวา
area_text = f"{rai} ไร่ {ngan} งาน {wa} ตารางวา"
print(area_text)

# ---------- ข้อท้าทาย (ไม่บังคับ) ----------
# ทำกลับด้าน: มีเนื้อที่เป็นตารางวา ให้แยกออกเป็น ไร่ งาน ตารางวา
# ห้ามแก้บรรทัดค่าตั้งต้นนี้
area_sq_wa = 2126
print(area_sq_wa)

# สร้างตัวแปร 3 ตัว ชื่อ rai_part, ngan_part และ wa_part
# สำหรับ 2126 ตารางวา ต้องได้ 5 ไร่ 1 งาน 26 ตารางวา
# เครื่องหมายที่ต้องใช้คือ // และ % ซึ่งอธิบายไว้ท้ายบทเรียน
rai_part = area_sq_wa // 400
ngan_part = (area_sq_wa % 400) // 100
wa_part = area_sq_wa % 100
print(rai_part, ngan_part, wa_part)

